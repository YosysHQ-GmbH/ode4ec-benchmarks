import runner

MUTATE = Path(__file__).resolve().parent / "mutate.py"
WIRE = re.compile(
    r"^\s*wire(?: width (\d+))?(?: upto)?(?: offset -?\d+)?"
    r"(?: (input|output|inout) \d+)?(?: signed)? (\S+)$"
)
ENGINES = {"pdr": "abc pdr", "suprove": "aiger suprove", "rIC3": "aiger rIC3"}
REACHED = re.compile(
    r"[Rr]eached cover statement (?:\S+ at|in step \d+ at \S+) cover\.v:(\d+)"
)
UNREACHED = re.compile(r"[Uu]nreached cover statement (?:\S+ at|at \S+) cover\.v:(\d+)")


class CheckError(ValueError):
    pass


def ports(il, module):
    out, inside = [], False
    for ln in Path(il).read_text().split("\n"):
        if ln.startswith("module "):
            inside = ln.split()[1] == f"\\{module}"
        elif inside and ln == "end":
            break
        elif inside and (m := WIRE.match(ln)) and m.group(2):
            out.append(
                {"name": m.group(3), "dir": m.group(2), "width": int(m.group(1) or 1)}
            )
    if not out:
        raise CheckError(f"{il}: module {module} has no ports")
    return sorted(out, key=lambda p: p["name"])


def esc(name):
    if not name.startswith("\\"):
        raise CheckError(f"port {name} is not a public name")
    return name + " "


def port_diff(gold, gate):
    return (sorted({*gold} ^ {*gate}) or sorted(n for n in gold if gold[n] != gate[n]))[
        :5
    ]


def vrange(p):
    return f"[{p['width'] - 1}:0] " if p["width"] > 1 else ""


def comma_lines(items, indent):
    return [
        f"{indent}{x}{',' if i < len(items) - 1 else ''}" for i, x in enumerate(items)
    ]


def module_head(name, ins, ens):
    decls = [f"input {vrange(p)}{esc(p['name'])}" for p in ins] + [
        f"input {e}" for e in ens
    ]
    return [
        "// generated by bench/checks.py",
        f"module {name} (",
        *comma_lines(decls, "    "),
        ");",
    ]


def instance(module, name, conn):
    return [f"    {module} {name} (", *comma_lines(conn, "        "), "    );"]


def always_head(ens):
    return (
        f"    always @* if ({' && '.join(ens)}) begin" if ens else "    always @* begin"
    )


def miter_text(case, gate_ports):
    gold = {p["name"]: p for p in case["ports"]}
    gate = {p["name"]: p for p in gate_ports}
    if gold != gate:
        raise CheckError(f"gold and gate ports differ: {port_diff(gold, gate)}")
    if any(p["dir"] == "inout" for p in gold.values()):
        raise CheckError("inout ports are not supported by the generated miter")
    excl = {"\\" + e["port"]: e["why"] for e in case["compare"]["exclude"]}
    outs = [
        p
        for p in gold.values()
        if p["dir"] == "output" and p["name"] not in excl and p["width"] > 0
    ]
    ins = [p for p in gold.values() if p["dir"] == "input" and p["width"] > 0]
    names = {p["name"] for p in ins}
    for sig in [
        *(c["name"] for c in case["clocks"]),
        *(r["name"] for r in case["resets"]),
    ]:
        if "\\" + sig not in names:
            raise CheckError(f"clock/reset {sig} is not an input port")
    if unknown := sorted(
        set(excl) - {p["name"] for p in gold.values() if p["dir"] == "output"}
    ):
        raise CheckError(f"[compare] exclude names no output: {unknown}")
    if not outs:
        raise CheckError("no output to compare")
    ens = enables(case)
    if clash := sorted(set(ens) & {p["name"].lstrip("\\") for p in gold.values()}):
        raise CheckError(f"port names clash with the miter's enables: {clash}")
    lines = module_head("miter", ins, ens)
    lines += [
        f"    wire {vrange(p)}gold_{i}, gate_{i};  // {p['name']}"
        for i, p in enumerate(outs)
    ]
    lines += [f"    // not compared: {n}: {why}" for n, why in sorted(excl.items())]
    for side in ("gold", "gate"):
        conn = [f".{esc(p['name'])}({esc(p['name'])})" for p in ins]
        conn += [f".{esc(p['name'])}({side}_{i})" for i, p in enumerate(outs)]
        conn += [f".{esc(n)}()" for n in sorted(excl)]
        lines += instance(f"{side}_top", side, conn)
    lines.append(always_head(ens))
    lines += [
        f"        assert (gold_{i} == gate_{i});  // {p['name']}"
        for i, p in enumerate(outs)
    ]
    return "\n".join([*lines, "    end", "endmodule", ""])


def enables(case):
    return [f"__bench_en_{i}" for i in range(len(case["resets"]))]


def reset_script(case):
    out = []
    for r, en in zip(case["resets"], enables(case), strict=True):
        clk = next(c for c in case["clocks"] if c["name"] == r["clock"])
        edge, hold = f"-{clk['edge']} {clk['name']}", r["hold"]
        out += [
            f"fminit -seq {r['name']} {','.join([str(r['active'])] * hold + ["'z"])} {edge}",
            f"fminit -seq {en} {','.join(['0'] * hold + ['1'])} {edge}",
        ]
    return "".join(f"{ln}\n" for ln in out)


def sby_text(case, timeout):
    tasks = "\n".join(ENGINES)
    modes = "\n".join(f"{t}: mode prove" for t in ENGINES)
    engines = "\n".join(f"{t}: {e}" for t, e in ENGINES.items())
    resets = reset_script(case)
    return f"""[tasks]
{tasks}

[options]
{modes}
timeout {timeout}

[engines]
{engines}

[script]
read_rtlil gold.il
read_liberty -ignore_miss_func cells.lib
read_rtlil gate.il
chformal -assert -remove
chformal -cover -remove
select -assert-none t:$assume t:$check t:$live t:$fair
setundef -init -zero gold_top
read_verilog -formal miter.v
hierarchy -check -top miter
proc
flatten
rename -hide w:*[[]* x:* %d
{resets}async2sync
clk2fflogic
techmap t:$shiftx
setundef -zero
setundef -undriven -zero

[files]
gold.il
gate.il
miter.v
cells.lib
"""


def cover_text(case):
    ins = [p for p in case["ports"] if p["dir"] == "input" and p["width"] > 0]
    outs = [p for p in case["ports"] if p["dir"] == "output" and p["width"] > 0]
    if any(p["dir"] == "inout" for p in case["ports"]):
        raise CheckError("inout ports are not supported by the generated cover")
    ens = enables(case)
    conn = [f".{esc(p['name'])}({esc(p['name'])})" for p in ins]
    conn += [f".{esc(p['name'])}(out_{i})" for i, p in enumerate(outs)]
    lines = module_head("cover_top", ins, ens)
    lines += [
        f"    wire {vrange(p)}out_{i};  // {p['name']}" for i, p in enumerate(outs)
    ]
    lines += instance("gold_top", "gold", conn)
    lines.append(always_head(ens))
    lines += [
        f"        cover (^out_{i} !== 1'bx);  // {p['name']}"
        for i, p in enumerate(outs)
    ]
    return "\n".join([*lines, "    end", "endmodule", ""])


def cover_sby_text(case, depth, engine, timeout):
    resets = reset_script(case)
    return f"""[options]
mode cover
depth {depth}
timeout {timeout}

[engines]
{engine}

[script]
read_rtlil gold.il
chformal -assert -remove
chformal -cover -remove
select -assert-none t:$assume t:$check t:$live t:$fair
read_verilog -formal cover.v
hierarchy -check -top cover_top
proc
flatten
{resets}async2sync
clk2fflogic
opt_expr -keepdc -undriven
opt_clean
xprop -formal -split-ports -assume-def-inputs cover_top

[files]
gold.il
cover.v
"""


def cover_lines(log_text):
    reached = {int(n) for n in REACHED.findall(log_text)}
    unreached = {int(n) for n in UNREACHED.findall(log_text)}
    return reached - unreached, unreached


def run_cover(bdir, odir, limit, mem_cap, versions, depth=64, engine="smtbmc yices"):
    bdir, odir = Path(bdir).resolve(), Path(odir).resolve()
    case = json.loads((bdir / "case.json").read_text())
    row = {
        "check": "cover",
        "engine": engine,
        "reset_assumed": bool(case["resets"]),
        "miter": "cover",
        "workdir": odir / "cover",
    }
    try:
        text = cover_text(case)
    except CheckError as e:
        return [{**row, "result": "ERROR", "reason": f"cover: {e}", "check_hash": ""}]
    sby = cover_sby_text(case, depth, engine, limit)
    (bdir / "cover.v").write_text(text)
    (bdir / "cover.sby").write_text(sby)
    odir.mkdir(parents=True, exist_ok=True)
    t0, oom0 = time.time(), runner.oom_kills()
    cmd, oomf = runner.capped(
        ["sby", "-f", "-d", str(odir / "cover"), str(bdir / "cover.sby")]
    )
    p = subprocess.Popen(
        cmd,
        cwd=bdir,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        start_new_session=True,
    )
    try:
        p.wait(timeout=limit + 300)
        killed = False
    except subprocess.TimeoutExpired:
        runner.kill_tree(p.pid)
        p.wait()
        killed = True
    runner.reap_leftovers()
    row.update(secs=round(time.time() - t0, 1), check_hash=digest(sby, text, versions))
    log = odir / "cover" / "logfile.txt"
    log_text = log.read_text(errors="replace") if log.exists() else ""
    port_at = {
        i + 1: ln.rsplit("// ", 1)[1]
        for i, ln in enumerate(text.split("\n"))
        if "cover (" in ln
    }
    reached, unreached = cover_lines(log_text)
    if runner.oom_killed(oomf, oom0):
        return [
            {
                **row,
                "result": "ERROR",
                "reason": f"OOM: killed by the {mem_cap} memory cap",
            }
        ]
    missing = [port_at[n] for n in sorted(set(port_at) - reached)]
    done = f"{len(port_at) - len(missing)}/{len(port_at)} output ports defined"
    if not missing:
        return [{**row, "result": "COVERED", "reason": f"{done} within {depth} steps"}]
    if killed or "DONE (TIMEOUT" in log_text:
        return [
            {
                **row,
                "result": "UNKNOWN",
                "reason": f"timeout: {done} so far; open: {', '.join(missing[:5])}",
            }
        ]
    if not reached and not unreached:
        last = re.findall(r"ERROR.*", log_text)[-1:] or ["no cover summary"]
        return [{**row, "result": "ERROR", "reason": f"sby: {last[0][:200]}"}]
    return [
        {
            **row,
            "result": "NOT_COVERED",
            "reason": f"{done} within {depth} steps; not: {', '.join(missing[:5])}",
        }
    ]


def input_hash(bdir):
    h = hashlib.sha256()
    for name in ("gold.il", "gate.il"):
        for ln in (Path(bdir) / name).read_text().split("\n"):
            if not ln.startswith("# Generated by") and not ln.lstrip().startswith(
                "attribute \\src "
            ):
                h.update(ln.encode() + b"\n")
    return h.hexdigest()[:16]


def gate_cells(bdir):
    return sum(
        ln.startswith("  cell ")
        for ln in (Path(bdir) / "gate.il").read_text().split("\n")
    )


def mutants(bdir, n=4):
    bdir = Path(bdir).resolve()
    case = json.loads((bdir / "case.json").read_text())
    mroot, made = bdir / "mutants", bdir / "mutants" / "made_from"
    if not (made.exists() and made.read_text() == case["input_hash"]):
        shutil.rmtree(mroot, ignore_errors=True)
        mroot.mkdir()
        cmd, oomf = runner.capped(
            [
                sys.executable,
                str(MUTATE),
                str(bdir / "gate.il"),
                str(mroot / "raw"),
                "--module",
                "gate_top",
                "--n",
                str(n),
                "--seed",
                "1",
                "--liberty",
                str(bdir / "cells.lib"),
                "--max-ff-depth",
                "1",
            ]
        )
        oom0 = runner.oom_kills()
        p = subprocess.run(cmd, capture_output=True, text=True, check=False)
        (mroot / "mutate.log").write_text(p.stdout + p.stderr)
        if runner.oom_killed(oomf, oom0) or p.returncode:
            raise CheckError(
                f"mutate.py failed: {(p.stdout + p.stderr).strip()[-200:]}"
            )
        applied = dict(
            re.findall(
                r"^(m\d+): (.*)$",
                (mroot / "raw" / "mutations.ys").read_text(),
                re.MULTILINE,
            )
        )
        for m in sorted((mroot / "raw").glob("m*.il")):
            mb = mroot / m.stem
            mb.mkdir()
            for f in ("gold.il", "cells.lib"):
                (mb / f).symlink_to(bdir / f)
            m.rename(mb / "gate.il")
            mcase = {
                **case,
                "variant": m.stem,
                "mutation": applied.get(m.stem, ""),
                "input_hash": input_hash(mb),
            }
            (mb / "case.json").write_text(json.dumps(mcase, indent=1) + "\n")
        made.write_text(case["input_hash"])
    return sorted(p for p in mroot.glob("m[0-9]*") if p.is_dir())


def digest(*parts):
    h = hashlib.sha256()
    for p in parts:
        h.update(p.encode() if isinstance(p, str) else p)
    return h.hexdigest()[:16]


def run_eqy(bdir, odir, limit, jobs, mem_cap, versions):
    bdir, odir = Path(bdir).resolve(), Path(odir).resolve()
    odir.mkdir(parents=True, exist_ok=True)
    text = runner.eqy_text(
        bdir / "gold.il",
        bdir / "gate.il",
        [f"read_liberty -ignore_miss_func {bdir / 'cells.lib'}"],
        limit,
    )
    (odir / "case.eqy").write_text(text)
    row = runner.eqy_run(
        odir / "case.eqy", odir / "eqy", odir / "eqy.log", jobs, limit, mem_cap
    )
    return [
        {
            "check": "eqy",
            "engine": "abc pdr",
            "result": row["result"],
            "reason": row["reason"],
            "secs": row["wall_secs"],
            "reset_assumed": False,
            "miter": "eqy",
            "check_hash": digest(text, versions, str(jobs)),
            "workdir": odir / "eqy",
        }
    ]


def run_sby_mi(bdir, odir, limit, mem_cap, versions):
    bdir, odir = Path(bdir).resolve(), Path(odir).resolve()
    case = json.loads((bdir / "case.json").read_text())
    try:
        miter = miter_text(case, ports(bdir / "gate.il", "gate_top"))
    except CheckError as e:
        return [
            {
                "check": "sby_mi",
                "engine": "-",
                "result": "ERROR",
                "reason": f"miter: {e}",
                "reset_assumed": bool(case["resets"]),
                "miter": "generated",
                "check_hash": "",
                "workdir": bdir,
            }
        ]
    sby = sby_text(case, limit)
    (bdir / "miter.v").write_text(miter)
    (bdir / "miter.sby").write_text(sby)
    rows = []
    for r in runner.run_sby(bdir / "miter.sby", list(ENGINES), limit, mem_cap, odir):
        engine = r["task"]
        rows.append(
            {
                "check": "sby_mi",
                "engine": engine,
                "result": r["result"],
                "reason": r["reason"],
                "secs": r["wall_secs"],
                "reset_assumed": bool(case["resets"]),
                "miter": "generated",
                "check_hash": digest(sby, miter, versions),
                "workdir": odir / f"sby_miter_{engine}",
            }
        )
    return rows
